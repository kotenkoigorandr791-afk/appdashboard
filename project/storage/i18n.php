function storage_supported_langs(): array
{
    return ['en', 'ru', 'uk', 'be', 'pl', 'cs'];
}

function storage_normalize_lang($lang): string
{
    $lang = strtolower(trim((string)$lang));
    if ($lang === 'ua') $lang = 'uk';
    if ($lang === 'by') $lang = 'be';
    return in_array($lang, storage_supported_langs(), true) ? $lang : 'en';
}

