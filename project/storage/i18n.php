function storage_boot_i18n($lang): string
{
    global $storageI18n, $storageLang;
    $storageLang = storage_normalize_lang($lang);
    $all = storage_i18n_dictionary();
    $storageI18n = ['en' => $all['en'], $storageLang => array_merge($all['en'], $all[$storageLang] ?? [])];
    return $storageLang;
}

function storage_i18n_payload(): array
{
    global $storageI18n, $storageLang;
    $lang = isset($storageLang) ? (string)$storageLang : 'en';
    return $storageI18n[$lang] ?? ($storageI18n['en'] ?? []);
}

function stg_t(string $key, array $vars = []): string
{
    global $storageI18n, $storageLang;
    $lang = isset($storageLang) ? (string)$storageLang : 'en';
    $text = (string)($storageI18n[$lang][$key] ?? $storageI18n['en'][$key] ?? $key);
    foreach ($vars as $name => $value) {
        $text = str_replace('{' . $name . '}', (string)$value, $text);
    }
    return $text;
}
